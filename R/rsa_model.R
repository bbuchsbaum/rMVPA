    cat("  |- Effective items per predictor (items / VIF): ",
        paste(sprintf("%s = %.1f", names(ipp), ipp), collapse = ", "), "\n", sep = "")
  }
  cat("\n")

  # Structure info
  cat("Structure:\n")

  # Block info
  if (!is.null(x$design$block_var)) {
    blocks <- table(x$design$block_var)
    cat("  |- Blocking: Present\n")
    cat("  |- Number of Blocks: ", length(blocks), "\n")
    cat("  |- Mean Block Size: ",
        format(mean(blocks), digits=2),
        " (SD: ",
        format(sd(blocks), digits=2),
        ")\n")
  } else {
    cat("  |- Blocking: None\n")
  }

  # Split info
  if (!is.null(x$design$split_by)) {
    split_info <- length(x$design$split_groups)
    cat("  |- Split Groups: ", split_info, "\n")
  } else {
    cat("  |- Split Groups: None\n")
  }

  cat("\n")
}


#' @export
#' @method print rsa_design
print.rsa_design <- function(x, ...) {
  # Print header
  cat("\n", "RSA Design", "\n")
  cat(rep("-", 20), "\n\n")

  # Formula
  cat("Formula:\n")
  cat("  |- ", deparse(x$formula), "\n\n")

  # Variables
  cat("Variables:\n")
  var_types <- sapply(x$data, function(v) {
    if (inherits(v, "dist")) "distance matrix"
    else if (is.matrix(v)) "matrix"
    else if (is.vector(v)) "vector"
    else "other"
  })

  cat("  |- Total Variables: ", length(x$data), "\n")
  for (i in seq_along(x$data)) {
    prefix <- if (i == length(x$data)) "  |-" else "  |-"
    cat(sprintf("%s %s: %s\n", prefix, names(x$data)[i], var_types[i]))
  }
  cat("\n")

  # Structure
  cat("Structure:\n")

  # Block info
  if (!is.null(x$block_var)) {
    blocks <- table(x$block_var)
    cat("  |- Blocking: Present\n")
    cat("  |- Number of Blocks: ", length(blocks), "\n")
    cat("  |- Block Sizes: ",
        paste0(names(blocks), ": ", blocks, collapse=", "), "\n")
  } else {
    cat("  |- Blocking: None\n")
  }

  # Include/exclude info
  if (!is.null(x$include)) {
    n_comparisons <- length(x$include)
    n_included <- sum(x$include)
    cat("  |- Comparisons: ",
        n_included,
        " of ",
        n_comparisons,
        sprintf(" (%.1f%%)", 100*n_included/n_comparisons), "\n")
  } else {
    cat("  |- Comparisons: All included\n")
  }

  cat("\n")
}


#' Construct an RSA (Representational Similarity Analysis) model
#'
#' This function creates an RSA model object by taking an MVPA (Multi-Variate Pattern Analysis) dataset and an RSA design.
#'
#' @seealso \code{\link{rsa_neural_rdm}} to compute the full neural correlation
#'   distance matrix from supplied observation-by-feature patterns.
#'
#' @param dataset An instance of an \code{mvpa_dataset}.
#' @param design An instance of an \code{rsa_design} created by \code{rsa_design()}.
#' @param distmethod A character string specifying the method used to compute distances between observations. 
#'        One of: \code{"pearson"}, \code{"spearman"} (default), or
#'        \code{"crossvalidated_euclidean"} (see below).
#' @param regtype A character string specifying the analysis method. 
#'        One of: \code{"pearson"}, \code{"spearman"}, \code{"lm"}, or \code{"rfit"} (defaults to "pearson").
#' @param check_collinearity Logical. When \code{regtype = "lm"}, stop if two
#'   predictor RDMs correlate above 0.99 or the design matrix is rank deficient.
#'   When \code{regtype} is \code{"lm"} or \code{"rfit"}, also warn if a model
#'   predictor has no usable variation or fewer than 10 effective items (see the section
#'   on effective support). Default is TRUE.
#' @param nneg A named list of variables (predictors) for which non-negative regression coefficients should be enforced 
#'        (only if \code{regtype="lm"}). Defaults to \code{NULL} (no constraints).
#' @param semipartial Logical indicating whether to compute semi-partial correlations in the \code{"lm"} case 
#'        (only if \code{nneg} is not used). Defaults to \code{FALSE}.
#' @param pattern_center Optional pattern-centering method applied to the stimulus-by-voxel matrix
#'   before distances are computed. Use \code{"stimulus_mean"} to subtract the across-stimulus
#'   mean pattern (Hanson-style). Default is \code{"none"}.
#' @param return_fingerprint Logical; if \code{TRUE}, project the per-unit
#'   neural pair-dissimilarity vector onto an orthonormal basis of the signal
#'   model RDM subspace and return the standardized model-space score vector
#'   alongside the standard outputs. For \code{\link{pair_rsa_design}} objects,
#'   predictors supplied through \code{nuisance} are excluded from this
#'   fingerprint basis. The basis is cached on the model spec and reused
#'   across ROIs/searchlight units. Default \code{FALSE}.
#' @param fingerprint_method Standardization method used when
#'   \code{return_fingerprint = TRUE}. One of \code{"pearson"} (centered/scaled)
#'   or \code{"spearman"} (rank-then-standardize). Default \code{"pearson"}.
#' @param fingerprint_basis Basis used to span the model RDM subspace when
#'   \code{return_fingerprint = TRUE}: \code{"pca"} (default) or \code{"qr"}.
#' @param measure Neural pair measurement: \code{"distance"} (default,
#'   correlation distance) or \code{"similarity"} (correlation). The choice
#'   applies after pattern centering and uses \code{distmethod} in either case.
#' @param statistic \code{NULL} preserves the existing output selected by
#'   \code{regtype}/\code{semipartial}. Use \code{"beta"} with ordinary,
#'   unconstrained \code{regtype = "lm"} to return raw model coefficients.
#'   Nuisance coefficients remain internal. Fixed designs cache QR coefficient
#'   queries; missing neural cells rebuild the query for eligible pairs.
#' @param contrasts Optional uniquely named list of named numeric coefficient
#'   weights, available with \code{statistic = "beta"}. Coefficient names are
#'   those in \code{design$model_mat}, plus \code{"(Intercept)"}. Outputs are
#'   named \code{contrast_<name>}.
#'
#' @param condition_labels Observation-aligned vector of condition IDs, required
#'   with \code{distmethod = "crossvalidated_euclidean"}. Repeated observations
#'   of a condition are averaged within each partition. Its unique values must
#'   equal \code{design$condition_ids}; the RDM order comes from the design.
#' @param crossval Independent-partition specification, for example
#'   \code{blocked_cross_validation(run_ids)}. Required only for crossvalidated
#'   Euclidean RSA and stored as \code{model$crossval}. Partitions must be disjoint,
#'   nonempty, exhaustive and at least two in number. Every condition must be
#'   observed in every partition. Missing cells are rejected at construction;
#'   nonfinite neural values fail the affected ROI rather than becoming zeros.
#'
#' @section Crossvalidated Euclidean distances:
#' For each distinct condition pair, average the inner products of its difference
#' patterns over all ordered pairs of independent partitions, then divide by the
#' number of features. This estimates a squared Euclidean distance per feature,
#'   in squared input units, and retains negative estimates. No whitening is
#' performed: this is not a Mahalanobis distance. All declared ROI features,
#' including constant columns, are retained in the normalization; nonfinite
#' columns fail the ROI instead of being removed by the shared ROI filter. Independent run IDs must be
#' supplied separately from the unique condition IDs used by the feature RDMs.
#' The caller is responsible for physical independence of partitions.
#'
#' This mode supports ordinary \code{rsa_design}, \code{measure = "distance"},
#' and the general searchlight dispatcher (\code{engine = "auto"} or
#' \code{"legacy"}). Optimized engines, including \code{"rsa_fast"}, are
#' explicitly rejected. Correlation fits use \code{regtype} to select Pearson
#' or Spearman association; historical correlation-distance behavior is unchanged.
#' It does not change \code{contrast_rsa_model}'s second-moment estimand.
#' Item permutations relabel conditions jointly across all partitions and must
#' preserve an explicit pair mask; specify suitable exchangeability blocks using
#' \code{block_var} and \code{keep_intra_run = TRUE} when retaining within-block
#' pairs. Pair masks alone do not establish exchangeability.
#'
#' @section Relational coefficients:
#' Combine \code{pair_rsa_design(..., modulation = ...)} with
#' \code{measure = "similarity", regtype = "lm", statistic = "beta"} to
#' estimate modulated relationships. For balanced one-to-one correspondence
#' and retrieval-observation intercepts, these coefficients equal regression
#' on matching-minus-nonmatching ERA scores. Unequal eligible candidate counts
#' generally imply a weighted reduction. Coefficient queries are conditional
#' on the specified measurement and fixed templates; they do not correct
#' first-level measurement bias or error in estimated neural predictors.
#' Pair cells are dependent. These outputs provide participant-level effects,
#' not calibrated standard errors or population inference. Existing label
#' permutations retain their joint-null restriction for multiple predictors;
#' they do not test a modulation coefficient conditional on other terms.
#'
#' @section Effective support of the design:
#' RDM entries are not independent observations. Every item enters
#' \code{n_items - 1} pairs, so the \code{n_pairs} entries of a vectorised RDM
#' carry on the order of \code{n_items} independent pieces of information, and
#' a regression coefficient's variance is inflated further by the predictor's
#' collinearity with the others (its VIF). The constructor computes
#' \code{n_items / VIF} for every predictor and stores the result as
#' \code{design_diagnostics} (see \code{\link{rsa_design_diagnostics}}). When
#' \code{regtype} is \code{"lm"} or \code{"rfit"} and a model predictor falls
#' below 10 effective items, it warns: that coefficient will vary across ROIs
#' largely through noise. This is a heuristic screen, not a test.
#'
#' For inference on RSA maps use \code{\link{run_permutation_searchlight}},
#' which permutes item labels and so carries the same dependence into the
#' null. For regression with multiple design predictors (including nuisance
#' predictors), this supports only an explicit joint no-association null via
#' \code{permutation_control(rsa_null = "joint")}; it does not provide
#' conditional inference on individual coefficients. The per-ROI t-values
#' returned by \code{regtype = "lm"} use pair-based degrees of freedom and
#' are anti-conservative.
#'
#' @return An object of class \code{"rsa_model"} (and \code{"list"}), containing:
#' \itemize{
#'   \item \code{dataset}    : the input dataset
#'   \item \code{design}     : the RSA design
#'   \item \code{distmethod} : the distance method used
#'   \item \code{regtype}    : the regression type
#'   \item \code{nneg}       : a named list of constrained variables, if any
#'   \item \code{semipartial}: whether to compute semi-partial correlations
#'   \item \code{design_diagnostics}: an \code{rsa_design_diagnostics} object
#'         (see \code{\link{rsa_design_diagnostics}})
#' }
#' @examples
#' # Create a random MVPA dataset (image data)
#' arr  <- array(rnorm(100 * 5), c(5, 5, 4, 5))   # 5 voxels x 5 voxels x 4 slices x 5 observations
#' sp   <- neuroim2::NeuroSpace(c(5, 5, 4, 5))
#' vec  <- neuroim2::NeuroVec(arr, sp)
#' mask <- neuroim2::LogicalNeuroVol(array(1, c(5, 5, 4)), neuroim2::NeuroSpace(c(5, 5, 4)))
#' mvpa_data <- mvpa_dataset(train_data = vec, mask = mask)
#'
#' # Create two random RDMs (distance matrices) over the 5 observations
#' data_mat  <- matrix(rnorm(5 * 10), 5, 10)
#' dismat1   <- dist(data_mat)
#' dismat2   <- dist(matrix(rnorm(5 * 10), 5, 10))
#' rdes <- rsa_design(~ dismat1 + dismat2,
#'                    list(dismat1 = dismat1, dismat2 = dismat2))
#'
#' # Create an RSA model with standard 'lm' (returns t-values):
#' rsa_mod <- rsa_model(mvpa_data, rdes, regtype = "lm")
#'
#' # Create an RSA model enforcing non-negativity for dismat2 only:
#' # Requires the 'glmnet' package to be installed
#' # rsa_mod_nneg <- rsa_model(mvpa_data, rdes, regtype="lm",
#' #                          nneg = list(dismat2 = TRUE))
#'
#' # Create an RSA model using 'lm' but returning semi-partial correlations:
#' rsa_mod_sp <- rsa_model(mvpa_data, rdes, regtype = "lm",
#'                         semipartial = TRUE)
#'
#' # Train the model using a trial-by-feature matrix
#' fit_params <- train_model(rsa_mod_sp, data_mat, y = NULL, indices = NULL)
#' # 'fit_params' = named vector of semi-partial correlations for each predictor
#'
#' # Condition-level feature RSA across three independent runs:
#' ids <- paste0("item", 1:6)
#' recording <- rep(1:2, each = 3)
#' pairs <- outer(recording, recording, `==`)
#' diag(pairs) <- FALSE
#' cv_design <- rsa_design(~ feature, list(feature = dist(1:6)),
#'                         condition_ids = ids, pair_mask = pairs)
#' cv_data <- gen_sample_dataset(c(2, 2, 2), 18, blocks = 3)$dataset
#' cv_model <- rsa_model(cv_data, cv_design,
#'   distmethod = "crossvalidated_euclidean",
#'   condition_labels = rep(ids, 3),
#'   crossval = blocked_cross_validation(rep(1:3, each = 6)))
#' # run_searchlight(cv_model, radius = 4, engine = "legacy")
#' # Six recordings with ten unique conditions each would retain 270 pairs.
#'
#' @export
rsa_model <- function(dataset,
                      design,
                      distmethod = "spearman",
                      regtype = "pearson",
                      check_collinearity = TRUE,
                      nneg = NULL,
                      semipartial = FALSE,
                      pattern_center = c("none", "stimulus_mean"),
                      return_fingerprint = FALSE,
                      fingerprint_method = c("pearson", "spearman"),
                      fingerprint_basis = c("pca", "qr"),
                      measure = c("distance", "similarity"),
                      statistic = NULL,
                      contrasts = NULL,
                      condition_labels = NULL,
                      crossval = NULL) {

  assert_that(inherits(dataset, "mvpa_dataset"))
  assert_that(inherits(design, "rsa_design"))

  distmethod <- match.arg(distmethod, c("pearson", "spearman", "crossvalidated_euclidean"))
  regtype    <- match.arg(regtype, c("pearson", "spearman", "lm", "rfit"))
  pattern_center <- match.arg(pattern_center)
  fingerprint_method <- match.arg(fingerprint_method)
  fingerprint_basis  <- match.arg(fingerprint_basis)
  measure <- match.arg(measure)
  if (!is.null(statistic)) statistic <- match.arg(statistic, "beta")
  if (!is.null(statistic) &&
      (!identical(regtype, "lm") || isTRUE(semipartial) || length(nneg))) {
    stop("`statistic = 'beta'` requires unconstrained regtype = 'lm' and semipartial = FALSE.",
         call. = FALSE)
  }
  if (!is.null(contrasts) && !identical(statistic, "beta")) {
    stop("`contrasts` requires statistic = 'beta'.", call. = FALSE)
  }
  
  # Check for glmnet if nneg constraints are provided
  if (!is.null(nneg) && length(nneg) > 0 && regtype == "lm") {
    if (!requireNamespace("glmnet", quietly = TRUE)) {
      stop("Package 'glmnet' is required for non-negative constraints. Please install it with: install.packages('glmnet')")
    }
  }
  
  # If using LM, optionally check for collinearity
  if (regtype == "lm" && check_collinearity && is.null(statistic)) {
    message("Checking design matrix for collinearity...")
    check_collinearity(design$model_mat)
    message("Collinearity check passed.")
  }

  # Verify that the number of observations in the dataset matches
  # the size expected by the RSA design. This prevents obscure
  # dimension errors later during model fitting.
  nobs_dataset <- {
    dims <- dim(dataset$train_data)
    if (is.null(dims)) length(dataset$train_data) else dims[length(dims)]
  }

  condition_design <- NULL
  if (identical(distmethod, "crossvalidated_euclidean")) {
    if (inherits(design, "pair_rsa_design") || !identical(measure, "distance")) {
      stop("Crossvalidated Euclidean RSA requires ordinary `rsa_design` and measure = 'distance'.", call. = FALSE)
    }
    condition_design <- .rsa_validate_partitions(design, condition_labels, crossval, nobs_dataset)
    if (any(!is.finite(unlist(design$model_mat)))) {
      stop("Crossvalidated RSA requires finite included predictor/nuisance pairs; supply an explicit `pair_mask`.", call. = FALSE)
    }
  } else if (!is.null(condition_labels) || !is.null(crossval)) {
    stop("`condition_labels` and `crossval` require distmethod = 'crossvalidated_euclidean'.", call. = FALSE)
  }

  if (inherits(design, "pair_rsa_design")) {
    pair_kind_chk <- design$pair_kind %||% "within"
    raw_len <- if (identical(pair_kind_chk, "between")) {
      design$n_a * design$n_b
    } else {
      choose(design$n_a, 2)
    }
    if (identical(pair_kind_chk, "between")) {
      max_row <- max(c(design$row_idx_a, design$row_idx_b))
      if (max_row > nobs_dataset) {
        stop(sprintf(
          "row_idx_a/row_idx_b reference row %d but dataset has %d observations.",
          max_row, nobs_dataset
        ), call. = FALSE)
      }
    } else if (!is.null(design$row_idx_a)) {
      max_row <- max(design$row_idx_a)
      min_row <- min(design$row_idx_a)
      if (max_row > nobs_dataset || min_row < 1L) {
        stop(sprintf(
          "row_idx_a references rows outside the dataset observations [1, %d].",
          nobs_dataset
        ), call. = FALSE)
      }
    } else if (design$n_a != nobs_dataset) {
      stop(sprintf(
        "Mismatch between dataset observations (%d) and pair_rsa_design n_a (%d). Use `row_idx_a` for within-mode subset/reordered designs.",
        nobs_dataset, design$n_a
      ), call. = FALSE)
    }
    expected_len <- if (!is.null(design$include)) sum(design$include) else raw_len
  } else {
    n_design_items <- .rsa_design_entry_size(design$data[[1L]])
    expected_items <- if (is.null(condition_design)) nobs_dataset else length(design$condition_ids)
    if (n_design_items != expected_items) {
      stop("Mismatch between dataset observations/conditions and RSA design items.", call. = FALSE)
    }
    expected_len <- choose(expected_items, 2)
    if (!is.null(design$include)) {
      expected_len <- sum(design$include)
    }
  }

  model_vec_len <- length(design$model_mat[[1]])
  if (model_vec_len != expected_len) {
    stop(sprintf(
      "Mismatch between dataset observations (%s) and RSA design length (%s).",
      nobs_dataset, model_vec_len
    ))
  }

  design_diagnostics <- rsa_design_diagnostics(design)
  if (regtype %in% c("lm", "rfit") && isTRUE(check_collinearity)) {
    .rsa_warn_effective_support(design_diagnostics, design)
  }

  fast_kernel <- NULL
  coefficient_query <- if (identical(statistic, "beta")) {
    .rsa_coefficient_query(design$model_mat, design$model_predictors, contrasts)
  } else NULL
  if (.rsa_fast_kernel_enabled() && is.null(statistic)) {
    fast_kernel <- .rsa_prepare_fast_kernel(
      design = design,
      regtype = regtype,
      distmethod = if (identical(distmethod, "crossvalidated_euclidean")) regtype else distmethod,
      semipartial = semipartial,
      nneg = nneg
    )
  }

  fingerprint_basis_obj <- NULL
  if (isTRUE(return_fingerprint)) {
    fingerprint_basis_obj <- .rsa_build_fingerprint_basis(
      design = design,
      method = fingerprint_method,
      basis  = fingerprint_basis
    )
  }

  # Create the RSA model object
  obj <- create_model_spec(
    "rsa_model",
    dataset,
    design,
    distmethod = distmethod,
    crossval = crossval,
    condition_labels = condition_labels,
    .condition_design = condition_design,
    .preserve_roi_features = identical(distmethod, "crossvalidated_euclidean"),
    regtype    = regtype,
    measure    = measure,
    statistic  = statistic,
    contrasts  = contrasts,
    nneg       = nneg,
    semipartial = semipartial,
    pattern_center = pattern_center,
    return_fingerprint = isTRUE(return_fingerprint),
    fingerprint_method = fingerprint_method,
    fingerprint_basis  = fingerprint_basis,
    design_diagnostics = design_diagnostics,
    .fast_kernel = fast_kernel,
    .coefficient_query = coefficient_query,
    .fingerprint_basis = fingerprint_basis_obj
  )
  obj
}


#' @noRd
.rsa_validate_partitions <- function(design, condition_labels, crossval, nobs) {
  ids <- design$condition_ids
  if (is.null(ids) || length(ids) < 2L) {
    stop("Crossvalidated RSA requires explicit `condition_ids` in RDM order in rsa_design().", call. = FALSE)
  }
  if (!is.atomic(condition_labels) || !is.null(dim(condition_labels)) ||
      length(condition_labels) != nobs || anyNA(condition_labels) ||
      !setequal(as.character(condition_labels), ids)) {
    stop("`condition_labels` must align with dataset rows and contain exactly the design's condition IDs.", call. = FALSE)
  }
  if (!inherits(crossval, "cross_validation")) {
    stop("Crossvalidated RSA requires an independent-partition `crossval` specification.", call. = FALSE)
  }
  nf <- get_nfolds(crossval)
  if (length(nf) != 1L || !is.finite(nf) || nf < 2L || nf != as.integer(nf)) {
    stop("Crossvalidated RSA requires at least two independent partitions.", call. = FALSE)
  }
  partitions <- lapply(seq_len(nf), function(i) partition_indices(crossval, i, n_samples = nobs))
  valid <- vapply(partitions, function(i) is.numeric(i) && length(i) > 0L &&
    all(is.finite(i)) && all(i == as.integer(i)) && all(i >= 1L & i <= nobs), logical(1))
  all_rows <- unlist(partitions, use.names = FALSE)
  if (!all(valid) || anyDuplicated(all_rows) || !setequal(all_rows, seq_len(nobs))) {
    stop("Crossvalidated RSA partitions must be nonempty, disjoint and cover every observation exactly once.", call. = FALSE)
  }
  complete <- vapply(partitions, function(i) all(ids %in% as.character(condition_labels[i])), logical(1))
  if (!all(complete)) {
    stop("Missing condition/partition observations: every condition must occur in every partition; no zero imputation or pairwise deletion is performed.", call. = FALSE)
  }
  mvpa_design(data.frame(condition = factor(condition_labels, levels = ids)),
              y_train = ~ condition,
              block_var = if (inherits(crossval, "blocked_cross_validation")) crossval$block_var else NULL)
}

#' @noRd
.rsa_crossvalidated_response <- function(obj, train_dat) {
  if (!is.matrix(train_dat) || !is.numeric(train_dat) || ncol(train_dat) < 1L ||
      nrow(train_dat) != length(obj$condition_labels) || any(!is.finite(train_dat))) {
    stop("Crossvalidated RSA requires finite observation-by-feature data with all declared rows; missing values are not imputed.", call. = FALSE)
  }
  folds <- compute_crossvalidated_means_sl(
    train_dat, obj$.condition_design, obj$crossval,
    estimation_method = "crossnobis", return_folds = TRUE
  )$fold_estimates
  if (!is.null(obj$design$item_perm)) {
    rows <- .rsa_apply_item_perm(seq_len(dim(folds)[1L]), obj$design$item_perm)
    folds <- folds[rows, , , drop = FALSE]
  }
  compute_crossnobis_distances_sl(folds)
}

#' @keywords internal
#' @noRd
.rsa_build_fingerprint_basis <- function(design, method, basis, tol = 1e-8) {
  predictor_names <- names(design$model_mat)
  model_predictors <- design$model_predictors
  if (is.null(model_predictors)) {
    model_predictors <- predictor_names
  }
  model_predictors <- intersect(model_predictors, predictor_names)
  if (length(model_predictors) == 0L) {
    stop("`return_fingerprint = TRUE` requires at least one signal model predictor; nuisance-only designs do not define a model-space fingerprint.",
         call. = FALSE)
  }
  mat <- do.call(cbind, design$model_mat[model_predictors])
  if (!is.matrix(mat) || ncol(mat) == 0L || nrow(mat) < 2L) {
    return(NULL)
  }
  storage.mode(mat) <- "double"
  X <- .rdm_model_space_standardize_matrix(mat, method = method, tol = tol,
                                           label = "model_mat")
  bf <- .rdm_model_space_basis(X, basis = basis, tol = tol)
  list(
    Q          = bf$Q,
    axis_names = bf$axis_names,
    method     = method,
    basis      = basis,
    p          = nrow(X),
    tol        = tol
  )
}


#' @keywords internal
#' @noRd
.rsa_project_fingerprint <- function(dvec, fp) {
  if (is.null(fp) || is.null(fp$Q)) return(NULL)
  if (length(dvec) != fp$p) return(NULL)

  v <- as.numeric(dvec)
  if (identical(fp$method, "spearman")) {
    v <- rank(v, ties.method = "average")
  }
  v <- v - mean(v)
  s <- stats::sd(v)
  if (!is.finite(s) || s <= fp$tol) {
    out <- rep(NA_real_, ncol(fp$Q))
    names(out) <- fp$axis_names
    return(out)
  }
  v <- v / s
  scores <- drop(crossprod(fp$Q, v)) / sqrt(fp$p - 1L)
  names(scores) <- fp$axis_names
  scores
}


#' @keywords internal
#' @noRd
.rsa_attach_fingerprint <- function(out, dvec, fp) {
  scores <- .rsa_project_fingerprint(dvec, fp)
  if (is.null(scores)) return(out)
  attr(out, "fingerprint") <- scores
  out
}

#' @rdname output_schema
#' @method output_schema rsa_model
#' @export
output_schema.rsa_model <- function(model) {
  predictor_names <- if (identical(model$statistic, "beta")) {
    rownames(model$.coefficient_query$query)
  } else names(model$design$model_mat)
  schema <- as.list(rep("scalar", length(predictor_names)))
  names(schema) <- predictor_names
