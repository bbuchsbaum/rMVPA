.rsa_prepare_fast_kernel <- function(design, regtype, distmethod, semipartial, nneg) {
  model_mat <- design$model_mat
  if (is.null(model_mat) || length(model_mat) == 0L) {
    return(NULL)
  }

  X <- do.call(cbind, model_mat)
  if (!is.matrix(X) || nrow(X) == 0L || ncol(X) == 0L) {
    return(NULL)
  }
  X <- as.matrix(X)
  storage.mode(X) <- "double"

  var_names <- colnames(X)
  if (is.null(var_names) || any(!nzchar(var_names))) {
    var_names <- names(model_mat)
  }
  if (is.null(var_names) || length(var_names) != ncol(X)) {
    var_names <- paste0("V", seq_len(ncol(X)))
  }
  colnames(X) <- var_names

  state <- list(cor = NULL, lm = NULL)

  if (regtype %in% c("pearson", "spearman")) {
    X_cor <- if (identical(distmethod, "spearman")) {
      apply(X, 2, rank, ties.method = "average")
    } else {
      X
    }
    X_cor <- as.matrix(X_cor)
    storage.mode(X_cor) <- "double"
    colnames(X_cor) <- var_names

    X_center <- sweep(X_cor, 2, colMeans(X_cor), FUN = "-")
    x_ss <- colSums(X_center^2)

    state$cor <- list(
      X_center = X_center,
      x_ss = x_ss,
      var_names = var_names,
      method = distmethod
    )
  }

  can_fast_lm <- identical(regtype, "lm") && (is.null(nneg) || length(nneg) == 0L) && !isTRUE(semipartial)
  if (can_fast_lm) {
    X_with_intercept <- cbind(`(Intercept)` = 1, X)
    df <- nrow(X_with_intercept) - ncol(X_with_intercept)

    if (df > 0L) {
      XtX <- crossprod(X_with_intercept)
      XtX_chol <- tryCatch(chol(XtX), error = function(e) NULL)
      if (!is.null(XtX_chol)) {
        XtX_inv <- chol2inv(XtX_chol)
        state$lm <- list(
          X_with_intercept = X_with_intercept,
          XtX_inv = XtX_inv,
          diag_xtx_inv = diag(XtX_inv),
          df = df,
          var_names = var_names
        )
      }
    }
  }

  if (is.null(state$cor) && is.null(state$lm)) {
    return(NULL)
  }
  state
}

run_cor_fast <- function(dvec, obj) {
  state <- obj$.fast_kernel$cor
  if (is.null(state)) {
    return(run_cor(dvec, obj))
  }

  dwork <- if (identical(state$method, "spearman")) {
    # Identical to rank(dvec, ties.method = "average"), with less overhead.
    as.vector(matrixStats::colRanks(matrix(as.numeric(dvec)), ties.method = "average",
                                    preserveShape = TRUE))
  } else {
    dvec
  }
  dwork <- as.numeric(dwork)

  d_center <- dwork - mean(dwork)
  d_ss <- sum(d_center^2)
  out <- rep(NA_real_, length(state$var_names))

  if (is.finite(d_ss) && d_ss > 0) {
    numer <- drop(crossprod(state$X_center, d_center))
    denom <- sqrt(state$x_ss * d_ss)
    keep <- is.finite(denom) & denom > 0
    out[keep] <- numer[keep] / denom[keep]
  }

  names(out) <- state$var_names
  out
}

run_lm_fast <- function(dvec, obj) {
  state <- obj$.fast_kernel$lm
  if (is.null(state)) {
    return(run_lm(dvec, obj))
  }

  y <- as.numeric(dvec)
  if (!all(is.finite(y))) {
    return(run_lm(dvec, obj))
  }
  xty <- drop(crossprod(state$X_with_intercept, y))
  beta <- drop(state$XtX_inv %*% xty)
  residual <- y - drop(state$X_with_intercept %*% beta)
  sigma2 <- sum(residual^2) / state$df
  if (!is.finite(sigma2) || sigma2 < 0) {
    return(run_lm(dvec, obj))
  }

  se <- sqrt(state$diag_xtx_inv * sigma2)
  tvals <- beta[-1] / se[-1]
  names(tvals) <- state$var_names
  tvals
}

# QR compilation keeps coefficient queries separate from pair-based t-values.
# Missing neural cells change the eligible design, so their queries are rebuilt.
.rsa_coefficient_query <- function(model_mat, model_names, contrasts = NULL, rows = NULL,
                                   validate_only = FALSE) {
  X <- cbind(`(Intercept)` = 1, do.call(cbind, model_mat))
  storage.mode(X) <- "double"
  if (is.null(rows)) rows <- seq_len(nrow(X))
  rows <- rows[apply(X[rows, , drop = FALSE], 1L, function(x) all(is.finite(x)))]
  Xk <- X[rows, , drop = FALSE]
  decomposition <- if (length(rows)) qr(Xk) else NULL
  if (!length(rows) || decomposition$rank < ncol(X)) {
    aliases <- if (length(rows)) {
      colnames(X)[decomposition$pivot[seq.int(decomposition$rank + 1L, ncol(X))]]
    } else colnames(X)
    stop("Relational coefficient design is rank deficient including its intercept; ",
         "aliased or unsupported columns: ", paste(aliases, collapse = ", "),
         ". Check background terms and eligible pairs.", call. = FALSE)
  }
  if (isTRUE(validate_only)) return(invisible(NULL))
  operator <- backsolve(qr.R(decomposition), t(qr.Q(decomposition)))
  operator <- operator[order(decomposition$pivot), , drop = FALSE]
  rownames(operator) <- colnames(X)
  query <- operator[model_names, , drop = FALSE]
  if (length(contrasts)) {
    if (!is.list(contrasts) || is.null(names(contrasts)) || anyNA(names(contrasts)) ||
        any(!nzchar(names(contrasts))) || anyDuplicated(names(contrasts))) {
      stop("`contrasts` must be a uniquely named list of named numeric coefficient weights.",
           call. = FALSE)
    }
    for (nm in names(contrasts)) {
      weights <- contrasts[[nm]]
      if (!is.numeric(weights) || !length(weights) || any(!is.finite(weights)) ||
          is.null(names(weights)) || anyNA(names(weights)) || any(!nzchar(names(weights))) ||
          anyDuplicated(names(weights)) || any(!names(weights) %in% colnames(X))) {
        stop("Contrast '", nm, "' must contain finite named weights for design coefficients.",
             call. = FALSE)
      }
      value <- matrix(drop(crossprod(weights, operator[names(weights), , drop = FALSE])),
                      nrow = 1L)
      rownames(value) <- paste0("contrast_", nm)
      query <- rbind(query, value)
    }
  }
  if (anyDuplicated(rownames(query))) {
    stop("Contrast output names must not duplicate model predictor names.", call. = FALSE)
  }
  if (!nrow(query)) {
    stop("Coefficient output requires model predictors or a requested contrast.", call. = FALSE)
  }
  list(query = query, rows = rows)
}

.rsa_coefficient_metrics <- function(y, obj) {
  state <- obj$.coefficient_query
  if (is.null(state) || any(!is.finite(y[state$rows]))) {
    state <- .rsa_coefficient_query(obj$design$model_mat, obj$design$model_predictors,
                                    obj$contrasts, rows = which(is.finite(y)))
  }
  out <- drop(state$query %*% y[state$rows])
  stats::setNames(as.numeric(out), rownames(state$query))
}

# Correlations are bilinear after row-wise centering/ranking and normalization.
# Contract fixed coefficient queries directly with the patterns, avoiding the
# neural pair matrix. Non-finite/degenerate patterns use the ordinary fallback.
.rsa_coefficient_contraction <- function(A, B, obj, between) {
  state <- obj$.coefficient_query
  if (is.null(state) || !all(is.finite(A)) || !all(is.finite(B))) return(NULL)
  left <- .era_normalize_similarity_rows(A, obj$distmethod)
  right <- .era_normalize_similarity_rows(B, obj$distmethod)
  if (!all(left$valid) || !all(right$valid)) return(NULL)
  n_pairs <- if (between) nrow(A) * nrow(B) else choose(nrow(A), 2L)
  eligible <- if (is.null(obj$design$include)) seq_len(n_pairs) else which(obj$design$include)
  out <- vapply(seq_len(nrow(state$query)), function(k) {
    weights <- numeric(n_pairs)
    weights[eligible[state$rows]] <- state$query[k, ]
    Q <- matrix(0, nrow(A), nrow(B))
    if (between) Q[] <- weights else Q[lower.tri(Q)] <- weights
    value <- sum((t(Q) %*% left$values) * right$values)
    if (identical(obj$measure, "similarity")) value else sum(weights) - value
  }, numeric(1L))
  stats::setNames(out, rownames(state$query))
}


################################################################################
# NEW: Constrained LM with glmnet
################################################################################
#' @keywords internal
#' @importFrom stats predict
#' @noRd
run_lm_constrained <- function(dvec, obj) {
  require_package("glmnet", "for non-negative constrained regression in RSA")
  
  # Convert list of vectors (predictors) into a matrix
  var_names <- names(obj$design$model_mat)
  X <- do.call(cbind, obj$design$model_mat)  # columns = predictors
  colnames(X) <- var_names
  
  # Identify which predictors should be constrained to be >= 0
  if (is.null(obj$nneg)) {
    stop("run_lm_constrained called, but obj$nneg is NULL.")
  }
  
  nneg_names <- names(obj$nneg)
  lower_lim_vec <- sapply(var_names, function(vn) {
    if (vn %in% nneg_names) 0 else -Inf
  })
  
  # Create penalty_factor vector - add a small penalty to non-negative terms
  # and zero penalty to unconstrained terms to avoid the "all penalty factors <= 0" error
  penalty_factor <- sapply(var_names, function(vn) {
    if (vn %in% nneg_names) 1e-5 else 0
  })
  
  # Use a small alpha (mixing parameter) to ensure stability
  alpha_val <- 1e-5
  
  # Fit glmnet with near-zero lambda and minimal penalty on non-negative variables
  fit <- tryCatch({
    glmnet::glmnet(
      x = X,
      y = dvec,
      alpha = alpha_val,                       
      lambda = 1e-5,                  
      penalty.factor = penalty_factor,
      lower.limits = lower_lim_vec,
      standardize = FALSE,
      intercept = TRUE
    )
  }, error = function(e) {
    # If error still occurs, try a different approach with all penalty factors = 1
    warning("First glmnet attempt failed, trying with uniform penalties: ", e$message)
    glmnet::glmnet(
      x = X,
      y = dvec,
      alpha = alpha_val,
      lambda = 1e-5,
      lower.limits = lower_lim_vec,
      standardize = FALSE,
      intercept = TRUE
    )
  })
  
  # Extract coefficients at smallest lambda
  lambda_min <- min(fit$lambda)
  
  # Properly extract coefficients - coef is S3 method
  coef_matrix <- predict(fit, type = "coefficients", s = lambda_min)
  # First row is intercept, we want rows 2:end
  betas <- as.numeric(coef_matrix)[-1]
  names(betas) <- var_names
  
  betas
}


################################################################################
# NEW: Semi-Partial LM
################################################################################
#' @keywords internal
#' @noRd
run_lm_semipartial <- function(dvec, obj) {
  # Compute semi-partial correlations from a single LM fit
  # sr_i = sign(t_i) * sqrt( (t_i^2 * MSE) / TSS )
  
  form <- paste("dvec", "~", paste(names(obj$design$model_mat), collapse = " + "))
  vnames <- names(obj$design$model_mat)
  obj$design$model_mat$dvec <- dvec
  
  fit  <- lm(form, data=obj$design$model_mat)
  smry <- summary(fit)
  
  # summary.lm omits aliased coefficients from its coefficient table. Keep the
  # design contract stable by filling only estimable terms into a full vector.
  coefficient_table <- coef(smry)
  tvals <- setNames(rep(NA_real_, length(vnames)), vnames)
  estimable <- intersect(vnames, rownames(coefficient_table))
  tvals[estimable] <- coefficient_table[estimable, "t value"]
  
  # Residual MSE
  MSE <- smry$sigma^2
  
  # TSS = total sum of squares of the outcome
  y_mod <- fit$model$dvec
  TSS   <- sum((y_mod - mean(y_mod))^2)
  
  # Compute sr_i
  sr2 <- (tvals^2 * MSE) / TSS
  sr  <- sign(tvals) * sqrt(sr2)
  
  sr
}


