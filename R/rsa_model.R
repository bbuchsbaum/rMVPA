#' @noRd
#' @keywords internal
sanitize <- function(name) {
  name <- gsub(":", ".", name)
  name <- gsub(" ", "", name)
  name <- gsub("[\\(\\)]", ".", name, perl=TRUE)
  name <- gsub(",", "_", name)
  name <- gsub("\\.$", "", name)
  name
}


#' Construct a design for an RSA (Representational Similarity Analysis) model
#'
#' This function constructs a design for an RSA model using the provided formula, data, and optional parameters.
#'
#' @param formula A formula expression specifying the dissimilarity-based regression function.
#' @param data A named list containing the dissimilarity matrices and any other auxiliary variables.
#' @param block_var An optional \code{formula}, \code{character} name or \code{integer} vector designating the block structure.
#' @param split_by An optional \code{formula} indicating grouping structure for evaluating test performance.
#' @param keep_intra_run A \code{logical} indicating whether to include within-run comparisons (default: FALSE).
#' @param nuisance Optional named list of nuisance RDMs or item-level
#'   variables using the same accepted forms as entries in \code{data}. These
#'   predictors are appended to the RSA model matrix, included in regression
#'   fits, and tagged as nuisance so \code{rsa_model(...,
#'   return_fingerprint = TRUE)} excludes them from model-space fingerprints.
#' @param pair_mask Optional logical vector in \code{dist}/lower-triangle order,
#'   or symmetric item-by-item logical matrix with a FALSE diagonal. TRUE retains
#'   that distinct-item pair. Missing values, wrong dimensions and empty selections
#'   are rejected. Intersects the existing \code{block_var} exclusion and applies
#'   identically to neural responses, predictors, nuisance terms and diagnostics.
#'   Included predictor/nuisance cells must be finite. \code{split_by} does not
#'   restrict fitted pairs. For within-recording comparisons, use a mask built
#'   from recording equality; \code{block_var} alone excludes same-block pairs.
#' @param condition_ids Optional unique IDs in the exact order of design items.
#'   Required for crossvalidated Euclidean RSA. Named RDMs and masks must match
#'   this order; these IDs identify conditions, not runs or repeated observations.
#' @return A list with class attributes "rsa_design" and "list", containing:
#'   \describe{
#'     \item{formula}{The input formula}
#'     \item{data}{The input data}
#'     \item{split_by}{The split_by formula}
#'     \item{split_groups}{Grouping structure for split_by}
#'     \item{block_var}{Block structure}
#'     \item{include}{Logical vector for including/excluding comparisons}
#'     \item{model_mat}{Model matrix generated by rsa_model_mat}
#'     \item{model_predictors}{Sanitized names of formula predictors}
#'     \item{nuisance_predictors}{Sanitized names of nuisance predictors}
#'   }
#' @details
#' The function creates an RSA design based on the input parameters. It checks the validity of the input data and
#' handles splitting conditions for evaluation of test performance. It also processes optional block structures and
#' within-run comparisons.
#' @importFrom assertthat assert_that
#' @export
#' @examples
#' dismat <- dist(matrix(rnorm(100*100), 100, 100))
#' rdes <- rsa_design(~ dismat, list(dismat=dismat))
rsa_design <- function(formula, data, block_var=NULL, split_by=NULL, keep_intra_run=FALSE, nuisance = list(),
                       pair_mask = NULL, condition_ids = NULL) {
  assert_that(purrr::is_formula(formula))
  if (!is.list(data) || is.null(names(data))) {
    stop("`data` must be a named list.", call. = FALSE)
  }
  nuisance <- if (is.null(nuisance)) list() else as.list(nuisance)
  if (length(nuisance) > 0L && (is.null(names(nuisance)) || any(!nzchar(names(nuisance))))) {
    stop("`nuisance` must be a named list when supplied.", call. = FALSE)
  }
  
  # Check that all variables are either matrices, "dist", or vectors
  nr <- sapply(c(data, nuisance), .rsa_design_entry_size)
  
  assert_that(all(nr == nr[1]), msg="all elements in 'data' and 'nuisance' must have the same number of rows")
  
  check_split <- function(split_var) {
    minSplits <- min(table(split_var))
    if (minSplits < 3) {
      stop(paste("error: splitting condition results in fewer than 3 observations in at least one set"))
    }
  }
  
  # Create split groups if split_by is provided
  split_groups <- if (!is.null(split_by)) {
    split_var <- parse_variable(split_by, data)
    split(seq_along(split_var), split_var)
  }
  
  # Process block_var if provided
  block_var <- if (!is.null(block_var)) {
    parse_variable(block_var, data)
  }
  
  # Include/exclude within-run comparisons based on keep_intra_run
  include <- if (!is.null(block_var) && !keep_intra_run) {
    as.vector(dist(block_var)) != 0
  }
  
  n_items <- as.integer(nr[1L])
  if (!is.null(condition_ids)) {
    if (!is.atomic(condition_ids) || !is.null(dim(condition_ids)) ||
        length(condition_ids) != n_items || anyNA(condition_ids) ||
        any(!nzchar(as.character(condition_ids))) || anyDuplicated(as.character(condition_ids))) {
      stop("`condition_ids` must contain one unique, nonmissing ID per design item.", call. = FALSE)
    }
    condition_ids <- as.character(condition_ids)
    for (entry in c(data, nuisance)) {
      ids <- if (inherits(entry, "dist")) attr(entry, "Labels") else
        if (is.matrix(entry)) rownames(entry) else NULL
      cols <- if (is.matrix(entry) && isSymmetric(unname(entry))) colnames(entry) else NULL
      if ((!is.null(ids) && !identical(ids, condition_ids)) ||
          (!is.null(cols) && !identical(cols, condition_ids))) {
        stop("RDM/item labels must match `condition_ids` in order.", call. = FALSE)
      }
    }
  }
  if (!is.null(pair_mask)) {
    pair_mask <- .rsa_validate_pair_mask(pair_mask, n_items, condition_ids)
    include <- if (is.null(include)) pair_mask else include & pair_mask
    if (!any(include)) stop("`pair_mask` leaves no eligible pairs.", call. = FALSE)
  }

  # Create the RSA design as a list
  des <- list(
    formula=formula,
    data=data,
    nuisance=nuisance,
    split_by=split_by,
    split_groups=split_groups,
    block_var=block_var,
    include=include,
    pair_mask=pair_mask,
    condition_ids=condition_ids
  )
  
  # Add model matrix to the design list
  mmat <- rsa_model_mat(des)
  if (!is.null(pair_mask) && any(!is.finite(unlist(mmat)))) {
    stop("Included predictor and nuisance pairs must be finite; use `pair_mask` to exclude missing cells.", call. = FALSE)
  }
  des$model_mat <- mmat
  model_names <- sanitize(labels(terms(formula)))
  nuisance_names <- sanitize(names(nuisance))
  if (anyDuplicated(c(model_names, nuisance_names))) {
    stop("Sanitized model/nuisance predictor names must be unique.",
         call. = FALSE)
  }
  des$model_predictors <- model_names
  des$nuisance_predictors <- nuisance_names
  des$predictor_roles <- stats::setNames(
    c(rep("model", length(model_names)), rep("nuisance", length(nuisance_names))),
    c(model_names, nuisance_names)
  )
  
  # Set the class attributes
  class(des) <- c("rsa_design", "list")
  
  # Return the RSA design
  des
}


#' @noRd
.rsa_design_entry_size <- function(x) {
  if (is.matrix(x)) {
    nrow(x)
  } else if (inherits(x, "dist")) {
    attr(x, "Size")
  } else if (is.vector(x)) {
    length(x)
  } else {
    stop(paste("illegal variable type", class(x)), call. = FALSE)
  }
}

#' @noRd
.rsa_validate_pair_mask <- function(pair_mask, n_items, condition_ids = NULL) {
  if (!is.logical(pair_mask) || anyNA(pair_mask)) {
    stop("`pair_mask` must be logical without missing values.", call. = FALSE)
  }
  if (is.matrix(pair_mask)) {
    if (!identical(dim(pair_mask), c(n_items, n_items)) ||
        !isSymmetric(unname(pair_mask)) || any(diag(pair_mask))) {
      stop("Matrix `pair_mask` must be square, symmetric, item-aligned, with a FALSE diagonal.", call. = FALSE)
    }
    if (!is.null(condition_ids)) {
      for (ids in dimnames(pair_mask)) {
        if (!is.null(ids) && !identical(ids, condition_ids)) {
          stop("`pair_mask` labels must match `condition_ids` in order.", call. = FALSE)
        }
      }
    }
    pair_mask <- pair_mask[lower.tri(pair_mask)]
  } else if (!is.null(dim(pair_mask)) || length(pair_mask) != choose(n_items, 2)) {
    stop("Vector `pair_mask` must have choose(n_items, 2) entries in lower-triangle order.", call. = FALSE)
  }
  unname(pair_mask)
}

#' @noRd
.rsa_design_vectorize_entries <- function(entries, include = NULL) {
  vmatlist <- lapply(entries, function(v) {
    if (inherits(v, "dist")) {
      as.vector(v)  # class "dist"
    } else if (is.matrix(v) && isSymmetric(v)) {
      v[lower.tri(v)]
    } else {
      as.vector(dist(v))
    }
  })

  if (!is.null(include)) {
    vmatlist <- lapply(vmatlist, function(v) v[include])
  }

  names(vmatlist) <- sanitize(names(entries))
  vmatlist
}

#' Construct a model matrix for an RSA (Representational Similarity Analysis) design
#'
#' This function constructs a model matrix for the given RSA design by processing distance matrices and other variables.
#'
#' @param rsa_des An RSA design object created by \code{rsa_design()}, containing formula, data, and optional parameters.
#' @return A named list of vectors, where:
#'   \itemize{
#'     \item Names correspond to sanitized variable names from the formula
#'     \item Each vector is the processed version of the corresponding input data
#'     \item For distance matrices, only the lower triangle is included
#'     \item If rsa_des$include is specified, vectors are subset accordingly
#'   }
#' @details
#' The function takes an RSA design object as input and processes the distance matrices and other variables to
#' construct a model matrix. It handles different types of input matrices, including symmetric and asymmetric
#' distance matrices, and can include or exclude within-run comparisons based on the RSA design.
#' @examples
#' dismat <- dist(matrix(rnorm(100*100), 100, 100))
#' rdes <- rsa_design(~ dismat, list(dismat=dismat))
#' rsa_model_mat(rdes)
#' @keywords internal
#' @noRd
rsa_model_mat <- function(rsa_des) {
  rvars <- labels(terms(rsa_des$formula))
  vset <- lapply(rvars, function(vname) {
    if (!(vname %in% names(rsa_des$data))) {
      stop("Variable '", vname, "' not found in RSA design data")
    }
    rsa_des$data[[vname]]
  })
  names(vset) <- rvars
  
  model_mat <- .rsa_design_vectorize_entries(vset, include = rsa_des$include)
  nuisance_mat <- .rsa_design_vectorize_entries(rsa_des$nuisance %||% list(),
                                                include = rsa_des$include)
  out <- c(model_mat, nuisance_mat)
  if (anyDuplicated(names(out))) {
    stop("Sanitized model/nuisance predictor names must be unique.",
         call. = FALSE)
  }
  out
}


#' @keywords internal
#' @noRd
run_rfit <- function(dvec, obj) {
  require_package("Rfit", "for robust regression in RSA")
  form <- paste("dvec", "~", paste(names(obj$design$model_mat), collapse = " + "))
  obj$design$model_mat$dvec <- dvec
  res <- Rfit::rfit(form, data=obj$design$model_mat)
  coef(res)[-1]
}


#' @keywords internal
#' @importFrom stats coef cor dist rnorm terms lm sd
#' @noRd
check_collinearity <- function(model_mat) {
  # Get the design matrix and names
  vnames <- names(model_mat)
  design_matrix <- as.matrix(model_mat)
  
  # Basic check - need at least 2 columns for collinearity
  if (ncol(design_matrix) > 1) {
    # Calculate correlation matrix and check for high correlations
    tryCatch({
      cor_matrix <- cor(design_matrix, use = "pairwise.complete.obs")
      diag(cor_matrix) <- 0
      if (any(abs(cor_matrix) > 0.99, na.rm = TRUE)) {
        high_cor_pairs <- which(abs(cor_matrix) > 0.99, arr.ind = TRUE)
        if (nrow(high_cor_pairs) > 0) {
          problem_vars <- apply(high_cor_pairs, 1, function(idx) {
            paste(vnames[c(idx[1], idx[2])], collapse = " and ")
          })
          stop(sprintf("Collinearity detected among predictors: %s. Consider removing one of the correlated variables.",
                       paste(problem_vars, collapse = "; ")))
        }
      }
      
      # Also check linear dependencies using QR decomposition
      qr_result <- qr(design_matrix)
      if (qr_result$rank < ncol(design_matrix)) {
        stop(sprintf("Design matrix is rank deficient (rank %d < %d columns). Some predictors are linear combinations of others.", 
                     qr_result$rank, ncol(design_matrix)))
      }
    }, error = function(e) {
      if (grepl("NA/NaN/Inf", e$message)) {
        stop("Cannot compute correlations due to NA/NaN/Inf values in predictor variables.")
      } else {
        stop(paste("Error checking collinearity:", e$message))
      }
    })
  }
}


#' Diagnose the effective support of an RSA design
#'
#' Summarises how much information an RSA design can bring to bear on each
#' predictor RDM.  RDM entries are not independent observations: every item
#' enters \code{n_items - 1} pairs, so the \code{n_pairs} entries of a
#' vectorised RDM carry on the order of \code{n_items} independent pieces of
#' information rather than \code{n_pairs}.  A regression coefficient's variance
#' is inflated further by the predictor's collinearity with the others, its
#' variance inflation factor (VIF).  The ratio \code{n_items / VIF} is
#' reported per predictor as the effective number of items supporting that
#' predictor's unique contribution.  Values below 10 mark a predictor whose
#' coefficient will vary across ROIs largely through noise.  This is a
#' heuristic screen, not a test; it flags designs that cannot separate their
#' predictors, it does not certify those that can.
#'
#' With an explicit \code{pair_mask}, only items participating in retained pairs
#' count toward effective support. The full item universe is still used for
#' condition alignment and item permutations.
#'
#' For \code{\link{pair_rsa_design}} objects in between-domain mode the item
#' count is \code{n_a + n_b}, since each item of either set enters every pair
#' with the other set.
#'
#' @param design An \code{rsa_design} or \code{pair_rsa_design}.
#'
#' @return An object of class \code{rsa_design_diagnostics}: a list with
#'   \code{n_items}, \code{n_pairs} (after any within-block exclusion),
#'   \code{n_predictors}, \code{predictors}, \code{predictor_roles},
#'   \code{max_abs_cor} and \code{max_abs_cor_pair} (the most correlated pair
#'   of predictors), \code{vif} (named, \code{Inf} when the design matrix is
#'   singular, \code{NA} for a constant predictor), \code{items_per_predictor}
#'   (\code{n_items / vif}), and \code{threshold} (10).
#'   \code{unsupported_predictors} names predictors with fewer than two
#'   distinct finite values; their VIF and effective item count are \code{NA},
#'   including when the design contains only that predictor.
#'
#' @seealso \code{\link{rsa_model}}, which computes this at construction and
#'   warns when a model predictor falls below the threshold, and
#'   \code{\link{run_permutation_searchlight}} for inference that respects the
#'   item-level dependence.
#'
#' @examples
#' set.seed(1)
#' items <- 12
#' shared <- matrix(rnorm(items * 4), items, 4)
#' a <- dist(shared)
#' b <- dist(shared + matrix(rnorm(items * 4, sd = 0.3), items, 4))
#' des <- rsa_design(~ a + b, list(a = a, b = b))
#' rsa_design_diagnostics(des)
#'
#' @export
rsa_design_diagnostics <- function(design) {
  assert_that(inherits(design, "rsa_design"))
  model_mat <- design$model_mat
  if (is.null(model_mat) || length(model_mat) == 0L) {
    stop("The RSA design has no predictors in `model_mat`.", call. = FALSE)
  }

  X <- as.matrix(do.call(cbind, model_mat))
  storage.mode(X) <- "double"
  colnames(X) <- names(model_mat)
  p       <- ncol(X)
  n_pairs <- nrow(X)
  n_items <- .rsa_design_n_items(design)
  if (!is.null(design$pair_mask)) {
    pairs <- which(lower.tri(matrix(FALSE, n_items, n_items)), arr.ind = TRUE)
    n_items <- length(unique(as.vector(pairs[design$include, , drop = FALSE])))
  }

  # Check variation even for a single predictor. A constant (or missing)
  # column cannot acquire support merely because no other columns exist.
  has_variation <- vapply(seq_len(p), function(j) {
    x <- X[, j]
    x <- x[is.finite(x)]
    length(x) > 1L && any(x != x[1L])
  }, logical(1))
  vif         <- stats::setNames(ifelse(has_variation, 1, NA_real_), colnames(X))
  max_abs_cor <- NA_real_
  max_pair    <- c(NA_character_, NA_character_)

  if (p > 1L) {
    # pairwise.complete.obs keeps an NA cell in one RDM from blanking the
    # whole correlation matrix; a constant column is NA on its own diagonal.
    R   <- suppressWarnings(stats::cor(X, use = "pairwise.complete.obs"))
    off <- abs(R)
    diag(off) <- NA_real_
    if (any(is.finite(off))) {
      idx         <- which(off == max(off, na.rm = TRUE), arr.ind = TRUE)[1L, ]
      max_abs_cor <- off[idx[1L], idx[2L]]
      max_pair    <- colnames(X)[sort(idx)]
    }

    good  <- has_variation & is.finite(diag(R))
    vif[] <- NA_real_
    if (sum(good) == 1L) {
      vif[good] <- 1
    } else if (sum(good) > 1L) {
      inv <- tryCatch(solve(R[good, good, drop = FALSE]), error = function(e) NULL)
      vif[good] <- if (is.null(inv)) Inf else pmax(diag(inv), 1)
    }
  }

  structure(
    list(
      n_items             = n_items,
      n_pairs             = n_pairs,
      n_predictors        = p,
      predictors          = colnames(X),
      predictor_roles     = design$predictor_roles,
      unsupported_predictors = colnames(X)[!has_variation],
      max_abs_cor         = max_abs_cor,
      max_abs_cor_pair    = max_pair,
      vif                 = vif,
      items_per_predictor = n_items / vif,
      threshold           = .rsa_min_items_per_predictor
    ),
    class = "rsa_design_diagnostics"
  )
}

#' @export
print.rsa_design_diagnostics <- function(x, ...) {
  cat("RSA design diagnostics\n")
  cat(sprintf("  items: %d   pairs: %d   predictors: %d\n",
              x$n_items, x$n_pairs, x$n_predictors))
  if (is.finite(x$max_abs_cor)) {
    cat(sprintf("  max |r| between predictors: %.3f (%s, %s)\n",
                x$max_abs_cor, x$max_abs_cor_pair[1L], x$max_abs_cor_pair[2L]))
  }
  cat("  effective items per predictor (items / VIF):\n")
  for (nm in x$predictors) {
    ipp  <- x$items_per_predictor[[nm]]
    flag <- if (nm %in% x$unsupported_predictors) {
      "  <- no usable variation"
    } else if (is.finite(ipp) && ipp < x$threshold) {
      "  <- below threshold"
    } else {
      ""
    }
    cat(sprintf("    %-20s VIF %7.2f   ~%6.1f items%s\n", nm, x$vif[[nm]], ipp, flag))
  }
  invisible(x)
}

# Effective items per predictor below which rsa_model() warns for regression
# regtypes.  A heuristic; see rsa_design_diagnostics().
.rsa_min_items_per_predictor <- 10

#' @keywords internal
#' @noRd
.rsa_design_n_items <- function(design) {
  if (!is.null(design$n_a)) {
    if (identical(design$pair_kind %||% "within", "between")) {
      return(as.integer(design$n_a + design$n_b))
    }
    return(as.integer(design$n_a))
  }
  if (!is.null(design$data) && length(design$data) > 0L) {
    return(as.integer(.rsa_design_entry_size(design$data[[1L]])))
  }
  if (is.null(design$include) && length(design$model_mat) > 0L) {
    len <- length(design$model_mat[[1L]])
    n   <- (1 + sqrt(1 + 8 * len)) / 2
    if (isTRUE(all.equal(n, round(n)))) return(as.integer(round(n)))
  }
  stop("Cannot determine the number of items in this RSA design.", call. = FALSE)
}

#' @keywords internal
#' @noRd
.rsa_warn_effective_support <- function(diagnostics, design) {
  preds <- design$model_predictors
  if (is.null(preds) || length(preds) == 0L) {
    preds <- names(diagnostics$items_per_predictor)
  }
  unsupported <- intersect(preds, diagnostics$unsupported_predictors)
  if (length(unsupported) > 0L) {
    warning(sprintf(
      "RSA predictor(s) '%s' have no usable variation (fewer than two distinct finite values); their coefficients are not identifiable and effective support is NA.",
      paste(unsupported, collapse = "', '")
    ), call. = FALSE)
  }
  ipp <- diagnostics$items_per_predictor[intersect(preds, names(diagnostics$items_per_predictor))]
  ipp <- ipp[is.finite(ipp)]
  if (length(ipp) == 0L || min(ipp) >= diagnostics$threshold) {
    return(invisible(FALSE))
  }
  worst    <- names(ipp)[which.min(ipp)]
  vif_w    <- diagnostics$vif[[worst]]
  shared   <- sprintf(paste0(
    "RDM entries share items, so the %d pairs carry roughly %d independent ",
    "observations. Per-ROI t-values overstate the evidence. See ",
    "run_permutation_searchlight() for the supported RSA null hypotheses; ",
    "conditional coefficient inference with other predictors is not implemented."),
    diagnostics$n_pairs, diagnostics$n_items)

  msg <- if (vif_w < 1.5) {
    # Item-limited: collinearity is not the problem, the item count is.
    sprintf(paste0(
      "RSA design has only %d items, which is ~%.1f effective items for predictor ",
      "'%s' (VIF = %.1f). Its coefficient will be unstable across ROIs. Add items ",
      "or pool runs. %s"),
      diagnostics$n_items, ipp[[worst]], worst, vif_w, shared)
  } else {
    cor_txt <- if (is.finite(diagnostics$max_abs_cor)) {
      sprintf("; max |r| between predictors = %.2f (%s vs %s)",
              diagnostics$max_abs_cor,
              diagnostics$max_abs_cor_pair[1L], diagnostics$max_abs_cor_pair[2L])
    } else {
      ""
    }
    sprintf(paste0(
      "RSA design supports predictor '%s' with only ~%.1f effective items ",
      "(%d items, VIF = %.1f%s). Variance inflation from collinear predictors ",
      "divides the item count further, and the coefficient will be unstable ",
      "across ROIs. Use fewer or less collinear predictors. %s"),
      worst, ipp[[worst]], diagnostics$n_items, vif_w, cor_txt, shared)
  }
  warning(msg, call. = FALSE)
  invisible(TRUE)
}

#' @keywords internal
#' @noRd
.rsa_apply_item_perm <- function(idx, perm, what = "item_perm") {
  if (is.null(perm)) return(idx)
  n <- length(idx)
  if (length(perm) != n || !identical(sort(as.integer(perm)), seq_len(n))) {
    stop(sprintf("`%s` must be a permutation of 1..%d (length %d supplied).",
                 what, n, length(perm)), call. = FALSE)
  }
  idx[perm]
}


#' @keywords internal
#' @importFrom stats coef cor dist rnorm terms lm sd
#' @noRd
run_lm <- function(dvec, obj) {
  # This is the standard LM approach that returns T-values for each predictor.
  form <- paste("dvec", "~", paste(names(obj$design$model_mat), collapse = " + "))
  vnames <- names(obj$design$model_mat)
  obj$design$model_mat$dvec <- dvec
  
  fit <- lm(form, data=obj$design$model_mat)
  # Return T-values (3rd column of coef summary)
  tvals <- coef(summary(fit))[-1, 3]
  names(tvals) <- vnames
  tvals
}


#' @keywords internal
#' @noRd
run_cor <- function(dvec, obj) {
  # For 'pearson' or 'spearman' regtype, we just do correlation with each predictor
  res <- sapply(obj$design$model_mat, function(x) cor(dvec, x, method=if (identical(obj$distmethod, "crossvalidated_euclidean")) obj$regtype else obj$distmethod))
  names(res) <- names(obj$design$model_mat)
  res
}

